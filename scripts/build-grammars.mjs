#!/usr/bin/env node
/**
 * build-grammars.mjs — compile each vendored tree-sitter grammar for the
 * current platform. Used by `npm run build` (local dev) and by the CI
 * workflow (which runs this once per platform in a matrix, then assembles
 * the per-platform .node files into prebuilds/).
 *
 * Usage:
 *   node scripts/build-grammars.mjs           # build all
 *   node scripts/build-grammars.mjs --rebuild  # force rebuild
 *   node scripts/build-grammars.mjs graphql lua  # build only the named grammars
 *
 * Each grammar subdirectory at grammars/<name>/ must contain:
 *   - binding.gyp        (node-gyp config)
 *   - binding.cc         (or bindings/node/binding.cc)
 *   - src/parser.c       (generated by tree-sitter generate; vendored)
 *   - src/scanner.{c,cc} (if the grammar uses external scanner)
 *   - package.json       (sub-package with name=tree-sitter-<name>)
 *
 * Output: grammars/<name>/build/Release/tree_sitter_<name>.node
 */
import { execSync } from "node:child_process";
import { existsSync, readdirSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const GRAMMARS_DIR = path.join(ROOT, "grammars");

const args = process.argv.slice(2);
const forceRebuild = args.includes("--rebuild");
const onlyNamed = args.filter((a) => !a.startsWith("--"));

function listGrammars() {
  if (onlyNamed.length > 0) return onlyNamed;
  return readdirSync(GRAMMARS_DIR).filter((entry) => {
    const full = path.join(GRAMMARS_DIR, entry);
    return statSync(full).isDirectory() && existsSync(path.join(full, "binding.gyp"));
  });
}

function findBindingCc(grammarDir) {
  const candidates = [
    path.join(grammarDir, "binding.cc"),
    path.join(grammarDir, "bindings", "node", "binding.cc"),
    path.join(grammarDir, "src", "binding.cc"),
  ];
  for (const c of candidates) {
    if (existsSync(c)) return c;
  }
  return null;
}

function buildOne(grammarName) {
  const grammarDir = path.join(GRAMMARS_DIR, grammarName);
  if (!existsSync(grammarDir)) {
    console.error(`[build-grammars] grammar directory not found: ${grammarDir}`);
    return false;
  }
  if (!existsSync(path.join(grammarDir, "binding.gyp"))) {
    console.error(`[build-grammars] ${grammarName}: no binding.gyp in ${grammarDir}`);
    return false;
  }
  const bindingCc = findBindingCc(grammarDir);
  if (!bindingCc) {
    console.error(`[build-grammars] ${grammarName}: no binding.cc found`);
    return false;
  }
  console.log(`[build-grammars] building ${grammarName}...`);
  try {
    // node-gyp rebuild ensures a fresh build (use --release for the optimized build).
    // The output lands at build/Release/tree_sitter_<name>.node.
    const cmd = forceRebuild
      ? `node-gyp rebuild --release --directory="${grammarDir}"`
      : `node-gyp build --release --directory="${grammarDir}"`;
    execSync(cmd, { stdio: "inherit", cwd: grammarDir });
    return true;
  } catch (e) {
    console.error(`[build-grammars] ${grammarName}: build FAILED:`, e.message);
    return false;
  }
}

const grammars = listGrammars();
console.log(`[build-grammars] grammars to build: ${grammars.join(", ")}`);
let ok = 0;
let failed = 0;
for (const g of grammars) {
  if (buildOne(g)) ok++;
  else failed++;
}
console.log(`[build-grammars] done: ${ok} ok, ${failed} failed`);
process.exit(failed === 0 ? 0 : 1);
